def norm(s: str) -> str:
    return s.lower().replace("ё", "е").replace("­", "")


def compile_topics():
    out = {}
    for subj, topics in TOPICS.items():
        out[subj] = {}
        for key, (_, words) in topics.items():
            alt = "|".join(re.escape(w) for w in sorted(words, key=len, reverse=True))
            out[subj][key] = re.compile(rf"(?<![а-яa-z0-9])(?:{alt})")
    return out


def main():
    text = json.loads((ROOT / "data" / "search.json").read_text(encoding="utf-8"))
    rx = compile_topics()
    files = {}
    for name, body in sorted(text.items()):
        subj = name.split("-", 1)[0]
        # Бланките са празни листове за отговори.
        if subj not in rx or "-blanka" in name:
            continue
        low = norm(body)
        hits = {k: len(r.findall(low)) for k, r in rx[subj].items()}
        top = max(hits.values(), default=0)
        hits = {k: v for k, v in sorted(hits.items(), key=lambda kv: -kv[1])
                if v >= MIN_HITS and v >= MIN_SHARE * top}
        if hits:
            files[name] = hits
    labels = {s: {k: v[0] for k, v in t.items()} for s, t in TOPICS.items()}
    data = {"topics": labels, "files": files}
    dst = ROOT / "data" / "topics.json"
    dst.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")

    print(f"{len(files)} файла с теми -> {dst.relative_to(ROOT)} ({dst.stat().st_size // 1024} KB)")
    for subj, topics in labels.items():
        cnt = {k: sum(1 for f, h in files.items() if f.startswith(subj + "-") and k in h) for k in topics}
        print(f"  {subj}: " + ", ".join(f"{topics[k]} {n}" for k, n in cnt.items()))


if __name__ == "__main__":
    main()
